using System;
using UnityEngine;

public class SmallSpiderAniController : MonoBehaviour
{
    [Header("Spider Reference")]
    private SmallSpiderMaker spider;

    [Header("Eye Animation Settings")]
    public float eyeRotationSpeed = 2f;
    public float eyeRotationAmount = 15f;
    public bool animateEyes = true;

    [Header("Leg Animation Settings")]
    public bool animateLegs = true;
    public float legWaveSpeed = 0.5f;
    public float legWaveAmount = 12f;
    public float legPhaseOffset = 0.5f; // Phase difference between legs
    public bool animateKnees = true;
    public float kneeFlexAmount = 30f; // Additional knee flexing

    private float eyeTimer = 0f;
    private float legTimer = 0f;
    
    // Store initial leg rotations
    private Quaternion[] initialLegRotations;
    private bool rotationsStored = false;

    public bool isPlaying = false; // controlled by MovieManager

    void Awake()
    {
        // Get the SmallSpiderMaker component that must be on the same GameObject.
        spider = GetComponent<SmallSpiderMaker>();
        
        if (spider == null)
        {
            Debug.LogError("SmallSpiderMaker script not found on the same GameObject as SmallSpiderAniController!");
        }
        
        // Now you can call StoreLegRotations safely after the maker runs.
        StoreLegRotations(); 
    }

    void Start()
    {
        if (spider != null)
        {
            StoreLegRotations();
        }
    }

    void Update()
    {
        if (!isPlaying) return; 

        if (spider == null)
        {
            Debug.LogWarning("SmallSpiderMaker reference is not set!");
            return;
        }

        // Store rotations if not done yet (in case spider was assigned after Start)
        if (!rotationsStored)
        {
            StoreLegRotations();
        }

        if (animateEyes)
        {
            AnimateEyes();
        }

        if (animateLegs)
        {
            AnimateLegs();
        }
    }

    void StoreLegRotations()
    {
        if (spider.legJoints == null || spider.legJoints.Length == 0)
            return;

        initialLegRotations = new Quaternion[spider.legJoints.Length];
        
        for (int i = 0; i < spider.legJoints.Length; i++)
        {
            if (spider.legJoints[i] != null)
            {
                initialLegRotations[i] = spider.legJoints[i].localRotation;
            }
        }
        
        rotationsStored = true;
    }

    void AnimateEyes()
    {
        eyeTimer += Time.deltaTime * eyeRotationSpeed;

        // Create oscillating rotation for pupils
        float xRotation = Mathf.Sin(eyeTimer) * eyeRotationAmount;
        float yRotation = Mathf.Cos(eyeTimer * 0.7f) * eyeRotationAmount;

        Quaternion targetRotation = Quaternion.Euler(xRotation, yRotation, 0);

        if (spider.leftPupilJoint != null)
        {
            spider.leftPupilJoint.localRotation = targetRotation;
        }

        if (spider.rightPupilJoint != null)
        {
            spider.rightPupilJoint.localRotation = targetRotation;
        }
    }

    void AnimateLegs()
    {
        if (spider.legJoints == null || spider.legJoints.Length == 0 || initialLegRotations == null)
            return;

        legTimer += Time.deltaTime * legWaveSpeed;

        // Animate each leg with a phase offset to create a wave effect
        for (int i = 0; i < spider.legJoints.Length; i++)
        {
            if (spider.legJoints[i] == null)
                continue;

            // Calculate phase for this leg
            float phase = legTimer + (i * legPhaseOffset);
            
            // Create wave motion
            float upDownRotation = Mathf.Sin(phase) * legWaveAmount;
            float twistRotation = Mathf.Cos(phase * 0.5f) * (legWaveAmount * 0.3f);
            
            // Create animation offset
            Quaternion animationOffset = Quaternion.Euler(upDownRotation, twistRotation, 0);
            
            // Apply animation relative to initial rotation
            spider.legJoints[i].localRotation = initialLegRotations[i] * animationOffset;
        }
    }

    // Example: Make eyes look at a target
    public void LookAtTarget(Vector3 worldTarget)
    {
        if (spider.leftPupilJoint != null)
        {
            Vector3 directionLeft = worldTarget - spider.leftPupilJoint.position;
            spider.leftPupilJoint.rotation = Quaternion.LookRotation(directionLeft);
        }

        if (spider.rightPupilJoint != null)
        {
            Vector3 directionRight = worldTarget - spider.rightPupilJoint.position;
            spider.rightPupilJoint.rotation = Quaternion.LookRotation(directionRight);
        }
    }

    // generated by Claude, walk animation for spider legs
    public void WalkAnimation(float speed)
    {
        if (spider.legJoints == null || spider.legJoints.Length < 8 || initialLegRotations == null)
            return;

        legTimer += Time.deltaTime * speed;

        // Define anatomical mapping (index-based)
        int L1 = 6, L2 = 7, L3 = 0, L4 = 1;
        int R1 = 5, R2 = 4, R3 = 3, R4 = 2;

        // Group A: support in stable state 1, swing in state 5
        int[] groupA = { L1, R2, L3, R4 }; // phase 0
        // Group B: support in stable state 5, swing in state 1
        int[] groupB = { R1, L2, R3, L4 }; // phase π

        for (int i = 0; i < spider.legJoints.Length; i++)
        {
            if (spider.legJoints[i] == null)
                continue;

            // Determine phase for each leg
            float phase = 0f;
            if (Array.Exists(groupA, leg => leg == i))
                phase = legTimer;
            else if (Array.Exists(groupB, leg => leg == i))
                phase = legTimer + Mathf.PI;
            
            // Leg lift amplitude (sin wave controls swing)
            float lift = Mathf.Max(0, Mathf.Sin(phase)) * 15f;

            // Forward/back swing (cos wave controls step motion)
            float forwardSwing = Mathf.Cos(phase) * 10f;

            // Apply animation: lift + forward swing
            spider.legJoints[i].localRotation =
                initialLegRotations[i] *
                Quaternion.Euler(-lift, forwardSwing, 0);
        }
    }

}